CREATE TABLE IF NOT EXISTS external_circuit_breaker (
    name VARCHAR(50) PRIMARY KEY,
    state VARCHAR(20) NOT NULL DEFAULT 'CLOSED',
    consecutive_failures INT NOT NULL DEFAULT 0,
    opened_until TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
ALTER TABLE external_circuit_breaker
    ADD COLUMN IF NOT EXISTS generation BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS probe_owner VARCHAR(100),
    ADD COLUMN IF NOT EXISTS probe_job_id BIGINT,
    ADD COLUMN IF NOT EXISTS probe_epoch BIGINT,
    ADD COLUMN IF NOT EXISTS probe_reserved_until TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS probe_call_id TEXT,
    ADD COLUMN IF NOT EXISTS probe_call_until TIMESTAMPTZ;
-- 이전 HALF_OPEN 행에는 소유자·generation이 없어 OPEN으로 되돌린다. 이전 호출자는 이미 멈춰 있어야 한다.
UPDATE external_circuit_breaker SET state='OPEN',generation=generation+1,
    opened_until=clock_timestamp() WHERE state='HALF_OPEN' AND probe_owner IS NULL;
ALTER TABLE external_circuit_breaker DROP CONSTRAINT IF EXISTS ck_external_circuit_breaker_open;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='external_circuit_breaker'::regclass AND conname='ck_circuit_contract') THEN
        ALTER TABLE external_circuit_breaker ADD CONSTRAINT ck_circuit_contract CHECK(
            generation>=0 AND consecutive_failures>=0 AND state IN ('CLOSED','OPEN','HALF_OPEN') AND
            (state<>'OPEN' OR opened_until IS NOT NULL) AND
            ((state='HALF_OPEN' AND probe_owner IS NOT NULL AND probe_job_id IS NOT NULL AND probe_epoch IS NOT NULL AND probe_epoch>=0
                AND probe_reserved_until IS NOT NULL) OR
             (state<>'HALF_OPEN' AND probe_owner IS NULL AND probe_job_id IS NULL AND probe_epoch IS NULL
                AND probe_reserved_until IS NULL AND probe_call_id IS NULL AND probe_call_until IS NULL)) AND
            ((probe_call_id IS NULL AND probe_call_until IS NULL) OR (probe_call_id IS NOT NULL AND probe_call_until IS NOT NULL)));
    END IF;
END $$;
CREATE TABLE IF NOT EXISTS external_circuit_result (
    breaker_name VARCHAR(50) NOT NULL REFERENCES external_circuit_breaker(name),
    call_id TEXT NOT NULL,
    generation BIGINT NOT NULL CHECK(generation>=0),
    probe_owner VARCHAR(100),
    outcome VARCHAR(20) NOT NULL CHECK(outcome IN ('SUCCESS','FAILURE','RATE_LIMIT','PERMANENT','CONFIGURATION')),
    applied BOOLEAN NOT NULL,
    resulting_state VARCHAR(20) NOT NULL CHECK(resulting_state IN ('CLOSED','OPEN','HALF_OPEN')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY(breaker_name,call_id)
);
CREATE INDEX IF NOT EXISTS idx_circuit_result_generation ON external_circuit_result(breaker_name,generation);
