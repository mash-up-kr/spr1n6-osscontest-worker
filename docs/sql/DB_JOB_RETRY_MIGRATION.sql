-- Core-owned upgrade proposal for databases with the previous DB_JOB_QUEUE_CONTRACT.
-- Stop old Workers and update DB scheduler arguments before deploying the new Worker.
-- This file is not executed automatically by the Worker.
BEGIN;

ALTER TABLE document ADD COLUMN IF NOT EXISTS execution_epoch BIGINT NOT NULL DEFAULT 0;
ALTER TABLE indexing_job ADD COLUMN IF NOT EXISTS outcome VARCHAR(40);
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = 'indexing_job' AND column_name = 'enqueue_seq') THEN
        ALTER TABLE indexing_job ADD COLUMN enqueue_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
        WITH ordered AS (SELECT id, row_number() OVER (ORDER BY created_at, id) AS seq FROM indexing_job)
        UPDATE indexing_job j SET enqueue_seq = o.seq FROM ordered o WHERE j.id = o.id;
        PERFORM setval(pg_get_serial_sequence('indexing_job', 'enqueue_seq'),
            COALESCE((SELECT MAX(enqueue_seq) FROM indexing_job), 1), EXISTS (SELECT 1 FROM indexing_job));
    END IF;
END;
$$;

-- Preserve issued generations so the first document-scoped claim cannot reuse an old token.
UPDATE document d SET execution_epoch = GREATEST(d.execution_epoch, previous.epoch)
FROM (SELECT document_id, MAX(execution_epoch) AS epoch FROM indexing_job GROUP BY document_id) previous
WHERE d.id = previous.document_id;

CREATE UNIQUE INDEX IF NOT EXISTS uq_indexing_job_enqueue_seq ON indexing_job(enqueue_seq);

DROP INDEX IF EXISTS idx_indexing_job_retry_admission;
DROP INDEX IF EXISTS idx_indexing_job_document_order;
CREATE INDEX idx_indexing_job_document_order ON indexing_job (document_id, enqueue_seq)
    WHERE status IN ('PENDING', 'PROCESSING', 'RETRY_WAIT');

DROP FUNCTION IF EXISTS recover_expired_indexing_jobs();
CREATE FUNCTION recover_expired_indexing_jobs(p_max_attempts INTEGER, p_base_delay_ms BIGINT)
RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE
    recovered_count BIGINT;
BEGIN
    IF p_max_attempts <= 0 OR p_base_delay_ms <= 0 THEN
        RAISE EXCEPTION 'Retry limit and base delay must be positive';
    END IF;
    WITH recovered AS (
        UPDATE indexing_job SET
            status = CASE WHEN attempt_count >= p_max_attempts THEN 'FAILED' ELSE 'RETRY_WAIT' END,
            next_retry_at = CASE
                WHEN attempt_count >= p_max_attempts THEN NULL
                WHEN status = 'RETRY_WAIT' AND next_retry_at IS NOT NULL THEN next_retry_at
                ELSE clock_timestamp() + GREATEST(1, floor(
                    p_base_delay_ms::double precision * GREATEST(attempt_count, 1) * (0.8 + random() * 0.4)
                )) * INTERVAL '1 millisecond' END,
            completed_at = CASE WHEN attempt_count >= p_max_attempts THEN clock_timestamp() ELSE NULL END,
            last_error_code = CASE WHEN attempt_count >= p_max_attempts THEN 'MAX_ATTEMPTS_EXCEEDED'
                ELSE 'LEASE_EXPIRED' END,
            worker_id = NULL, lease_until = NULL, updated_at = clock_timestamp()
        WHERE worker_id IS NOT NULL AND status IN ('PROCESSING', 'RETRY_WAIT')
          AND lease_until <= clock_timestamp()
        RETURNING id
    ) SELECT COUNT(*) INTO recovered_count FROM recovered;
    RETURN recovered_count;
END;
$$;

COMMIT;

-- Any DB scheduler must now call recover_expired_indexing_jobs(max_attempts, base_delay_ms)
-- with the same settings used by the Worker. Retry state preserves Job identity and order.
