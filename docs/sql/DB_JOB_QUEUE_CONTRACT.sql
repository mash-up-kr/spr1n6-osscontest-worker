    DROP COLUMN kafka_offset;

-- Backfill registration order deterministically for existing history, then continue the sequence.
WITH ordered AS (SELECT id, row_number() OVER (ORDER BY created_at, id) AS seq FROM indexing_job)
UPDATE indexing_job j SET enqueue_seq = o.seq FROM ordered o WHERE j.id = o.id;
SELECT setval(pg_get_serial_sequence('indexing_job', 'enqueue_seq'),
    COALESCE((SELECT MAX(enqueue_seq) FROM indexing_job), 1),
    EXISTS (SELECT 1 FROM indexing_job));

-- No issued lease survives cutover. New generations are issued by the next claim.
UPDATE indexing_job SET status = CASE WHEN status = 'PROCESSING' THEN 'PENDING' ELSE status END,
    worker_id = NULL, lease_until = NULL
WHERE status IN ('PENDING', 'PROCESSING', 'RETRY_WAIT');

ALTER TABLE document ADD CONSTRAINT ck_document_execution_epoch CHECK (execution_epoch >= 0);
ALTER TABLE indexing_job
    ADD CONSTRAINT uq_indexing_job_enqueue_seq UNIQUE (enqueue_seq),
    ADD CONSTRAINT ck_indexing_job_type CHECK (
        (job_type = 'INDEX' AND document_version_id IS NOT NULL) OR
        (job_type = 'DELETE' AND document_version_id IS NULL)
    ),
    ADD CONSTRAINT ck_indexing_job_epoch CHECK (execution_epoch >= 0),
    ADD CONSTRAINT ck_indexing_job_lease CHECK (
        (lease_until IS NULL AND (worker_id IS NULL OR status IN ('COMPLETED', 'FAILED'))) OR
        (status IN ('PROCESSING', 'RETRY_WAIT') AND worker_id IS NOT NULL AND lease_until IS NOT NULL)
    ),
    ADD CONSTRAINT fk_indexing_job_document FOREIGN KEY (document_id) REFERENCES document(id);

CREATE INDEX idx_indexing_job_document_order ON indexing_job (document_id, enqueue_seq)
    WHERE status IN ('PENDING', 'PROCESSING', 'RETRY_WAIT');
CREATE INDEX idx_indexing_job_expired_lease ON indexing_job (lease_until)
    WHERE worker_id IS NOT NULL AND status = 'PROCESSING';

-- The Worker passes its actual retry settings. Any DB scheduler must pass the same values.
-- No attempt or epoch is consumed here. A competing heartbeat rechecks this WHERE after locking.
CREATE FUNCTION recover_expired_indexing_jobs(p_max_attempts INTEGER, p_base_delay_ms BIGINT)
RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE
    recovered_count BIGINT;
BEGIN
    IF p_max_attempts <= 0 OR p_base_delay_ms <= 0 THEN
        RAISE EXCEPTION 'Retry limit and base delay must be positive';
    END IF;
    WITH recovered AS (
        UPDATE indexing_job SET
            status = CASE WHEN attempt_count >= p_max_attempts THEN 'FAILED' ELSE 'RETRY_WAIT' END,
            next_retry_at = CASE
                WHEN attempt_count >= p_max_attempts THEN NULL
                WHEN status = 'RETRY_WAIT' AND next_retry_at IS NOT NULL THEN next_retry_at
                ELSE clock_timestamp() + GREATEST(1, floor(
                    p_base_delay_ms::double precision * GREATEST(attempt_count, 1) * (0.8 + random() * 0.4)
                )) * INTERVAL '1 millisecond' END,
            completed_at = CASE WHEN attempt_count >= p_max_attempts THEN clock_timestamp() ELSE NULL END,
            last_error_code = CASE WHEN attempt_count >= p_max_attempts THEN 'MAX_ATTEMPTS_EXCEEDED'
                ELSE 'LEASE_EXPIRED' END,
            worker_id = NULL, lease_until = NULL, updated_at = clock_timestamp()
        WHERE worker_id IS NOT NULL AND status IN ('PROCESSING', 'RETRY_WAIT')
          AND lease_until <= clock_timestamp()
        RETURNING id
    ) SELECT COUNT(*) INTO recovered_count FROM recovered;
    RETURN recovered_count;
END;
$$;

